import { SHOPPING_AISLES, type ShoppingAisle } from '@family-os/schemas'

/** The fixed walk order (design.md) — canonical list lives in
    `@family-os/schemas` (the server route validates a correction's `category`
    against it too). Per-family reorder is a named non-goal. */
export const AISLES = SHOPPING_AISLES
export type Aisle = ShoppingAisle

/** Lowercase, collapse whitespace, strip punctuation — the shared key shape for
    dictionary lookups and family-wide overrides. Two names normalize equal iff a
    shopper would call them "the same item" written slightly differently
    ("Chicken Thighs" / "chicken thighs,"). */
export function normalizeItemName(name: string): string {
  return name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, '')
    .replace(/\s+/g, ' ')
}

