const NORMALIZED_ENTRIES: Array<{ key: string; aisle: Aisle }> = (
  Object.entries(DICTIONARY) as Array<[Aisle, string[]]>
)
  .flatMap(([aisle, words]) => words.map((word) => ({ key: normalizeItemName(word), aisle })))
  .sort((a, b) => b.key.length - a.key.length)

/** Match an already-normalized name against the dictionary. Whole-word/phrase
    match — "chicken" matches "boneless chicken thighs" but "rice" does not
    match "riceland" — checked longest-key-first so a multi-word entry
    ("peanut butter") wins over a shorter one it contains ("butter"). */
export function lookupDictionaryAisle(normalizedName: string): Aisle | null {
  const padded = ` ${normalizedName} `
  for (const { key, aisle } of NORMALIZED_ENTRIES) {
    if (padded.includes(` ${key} `)) return aisle
  }
  return null
}
